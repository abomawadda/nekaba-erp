// اختبار شاشة المالية في Chromium ضد البيانات الحقيقية — قراءة فقط (القيود لا تُحذف)، وصرف بلا قرار يجب أن يُرفض
import { createRequire } from 'node:module';
const { chromium } = createRequire(import.meta.url)('playwright');
const OUT = process.argv[2] || '.', BASE = 'http://127.0.0.1:8787/';
const proxy = process.env.HTTPS_PROXY ? { server: process.env.HTTPS_PROXY, bypass: '127.0.0.1,localhost' } : undefined;
const browser = await chromium.launch({ proxy });
let pass = 0, fail = 0; const ok = (c, m) => { if (c) pass++; else { fail++; console.log('✗', m); } };
const errors = [];
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, locale: 'ar-EG' });
const p = await ctx.newPage(); p.on('pageerror', e => errors.push(e.message)); p.on('dialog', d => d.accept());
const shot = n => p.screenshot({ path: `${OUT}/${n}.png`, fullPage: true });
const txt = () => p.textContent('.wrap');
await p.goto(BASE); await p.click('[data-tab=staff]');
await p.fill('[name=username]', 'zz_fin_ui'); await p.fill('[name=password]', 'FinUi#2026'); await p.click('#lf [type=submit]');
await p.waitForSelector('a[href="#/finance"]'); await p.click('a[href="#/finance"]');
await p.waitForSelector('[data-ledger="1102"]');
await p.fill('#pf [name=from]', '2022-01-01'); await p.click('#pf button'); await p.waitForSelector('[data-ledger="1102"]');
let t = await txt();
ok(/١٠٬٢٢٧٫٧٤|10,227\.74/.test(t), 'bank book balance 10,227.74'); ok(/٨٤٬٢٨٥|84,285/.test(t), 'custody 84,285');
ok(t.includes('العُهد المفتوحة') && t.includes('المصروفات حسب المجموعة'), 'summary sections'); await shot('f1-summary');
await p.click('[data-go="#/cheques"]'); await p.waitForSelector('[data-chq]');
ok((await p.$$('[data-chq]')).length === 232, '232 cheques'); await shot('f2-cheques');
await p.selectOption('#cf [name=status]', 'صادر'); await p.selectOption('#cf [name=purpose]', 'عهدة'); await p.click('#cf button');
await p.waitForTimeout(1200); ok((await p.$$('[data-chq]')).length === 7, '7 open advances');
await p.click('[data-chq]'); await p.waitForSelector('[data-act=settleNew]');
ok((await txt()).includes('تسوية العهدة'), 'settle button on open advance'); await shot('f3-cheque');
await p.click('[data-act=settleNew]'); await p.waitForSelector('#stf');
await p.locator('#stf [name=amt]').first().fill('100'); await p.waitForTimeout(200);
ok((await p.textContent('#stCalc')).includes('المتبقي'), 'live settle calc'); await shot('f4-settle-form');
await p.click('#modal [data-close]');
await p.goto(BASE + '#/trial'); await p.waitForSelector('[data-ledger]');
await p.fill('#pf [name=from]', '2022-01-01'); await p.click('#pf button'); await p.waitForSelector('.alert');
ok((await txt()).includes('الميزان متوازن'), 'trial balance balanced'); await shot('f5-trial');
await p.click('[data-ledger="1102"]'); await p.waitForSelector('.list [data-entry]');
ok((await p.$$('.list [data-entry]')).length > 50, 'bank ledger lines'); await shot('f6-ledger');
await p.locator('.list [data-entry]').first().click(); await p.waitForSelector('#modal h3');
ok((await p.textContent('#modal')).includes('مدين') && (await p.textContent('#modal')).includes('دائن'), 'entry modal'); await shot('f7-entry');
await p.click('#modal [data-close]');
await p.goto(BASE + '#/finance'); await p.waitForSelector('[data-act=chqNew]'); await p.click('[data-act=chqNew]');
await p.waitForSelector('#chf'); await p.fill('#chf [name=amount]', '100'); await p.fill('#chf [name=payee_name]', 'ZZ اختبار');
await p.fill('#chf [name=date]', '2026-11-22'); await p.click('#chf [type=submit]'); await p.waitForSelector('#ferr .alert');
ok((await p.textContent('#ferr')).includes('بقرار'), 'disbursement without decision rejected'); await shot('f8-reject');
ok(errors.length === 0, 'no JS errors: ' + errors.join(' | '));
await browser.close(); console.log(`\n${pass} نجح · ${fail} فشل`); process.exit(fail ? 1 : 0);
