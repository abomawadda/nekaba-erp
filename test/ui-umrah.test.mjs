await m.goto(BASE + '#/umrah'); await m.waitForSelector('form[data-devorder]');
let t = await m.textContent('.wrap'); ok(t.includes('ZZ عمرة رجب') && t.includes('شركة السياحة') && t.includes('متبقي 3'), 'umrah page shows offer + seats');
await m.fill('form[data-devorder] [name=travelers]', '4'); await m.click('form[data-devorder] button'); await m.waitForTimeout(1500);
