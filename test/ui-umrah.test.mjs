t = await m.textContent('.wrap'); ok(t.includes('2 أفراد') && t.includes('متبقي 1'), 'booked 2 travelers, 1 seat left');
await m.screenshot({ path: `${OUT}/u1-umrah.png`, fullPage: true });
ok(errors.length === 0, 'no JS errors: ' + errors.join(' | '));
await browser.close(); console.log(`\n${pass} نجح · ${fail} فشل`); process.exit(fail ? 1 : 0);
