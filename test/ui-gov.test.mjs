// اختبار شاشة المجلس في Chromium ضد الخادم الحي (حساب zz_live_test مؤقت يُزال بعده، ومعه اجتماع «ZZ اختبار»)
import { createRequire } from 'node:module';
const { chromium } = createRequire(import.meta.url)('playwright');
const OUT = process.argv[2] || '.', BASE = 'http://127.0.0.1:8787/';
const proxy = process.env.HTTPS_PROXY ? { server: process.env.HTTPS_PROXY, bypass: '127.0.0.1,localhost' } : undefined;
const browser = await chromium.launch({ proxy });
let pass = 0, fail = 0; const ok = (c, m) => { if (c) pass++; else { fail++; console.log('✗', m); } };
const errors = [];
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, locale: 'ar-EG' });
const p = await ctx.newPage(); p.on('pageerror', e => errors.push(e.message)); p.on('dialog', d => d.accept());
const shot = n => p.screenshot({ path: `${OUT}/${n}.png`, fullPage: true });
await p.goto(BASE); await p.click('[data-tab=staff]');
await p.fill('[name=username]', 'zz_live_test'); await p.fill('[name=password]', 'LiveTest#2026'); await p.click('#lf [type=submit]');
await p.waitForSelector('a[href="#/board"]'); await p.click('a[href="#/board"]');
await p.waitForSelector('[data-act=seatAdd]');
const txt = await p.textContent('.wrap');
ok(txt.includes('الدورة الاستثنائية'), 'term title'); ok(txt.includes('10 عضواً حالياً'), '10 current seats');
ok(txt.includes('رئيس المجلس') && txt.includes('أمين الصندوق'), 'roles shown'); ok(txt.includes('نتيجة الانتخابات'), 'candidates');
ok(txt.includes('مقاعد منتهية'), 'ended seats'); await shot('g1-board');
await p.click('[data-go="#/meetings"]'); await p.waitForSelector('[data-meet]');
ok((await p.$$('[data-meet]')).length === 31, '31 meetings listed'); await shot('g2-meetings');
await p.click('[data-meet]'); await p.waitForSelector('[data-act=meetEdit]');
ok((await p.textContent('.wrap')).includes('القرارات'), 'meeting detail'); await shot('g3-meeting');
await p.goto(BASE + '#/decisions'); await p.waitForSelector('#df');
ok((await p.$$('.list [data-meet]')).length >= 40, 'decisions register >= 40');
await p.fill('#df [name=q]', 'جدول'); await p.click('#df button'); await p.waitForTimeout(1500);
ok((await p.$$('.list [data-meet]')).length >= 1, 'decision search'); await shot('g4-decisions');
await p.goto(BASE + '#/meetings'); await p.waitForSelector('[data-act=meetNew]'); await p.click('[data-act=meetNew]');
await p.waitForSelector('#mtf'); await p.fill('#mtf [name=title]', 'ZZ اختبار اجتماع'); await p.fill('#mtf [name=meeting_date]', '2026-11-20');
await p.fill('#mtf [name=agenda]', 'بند أول\nبند ثاني');
await p.fill('[data-dec] [name=d_text]', 'ZZ قرار صرف دعم رحلة'); await p.selectOption('[data-dec] [name=d_category]', 'دعم نشاط');
await p.fill('[data-dec] [name=d_amount]', '5000'); await p.fill('[data-dec] [name=d_for]', '9');
await p.click('[data-act=decAdd]'); ok((await p.$$('[data-dec]')).length === 2, 'add decision row');
await p.locator('[data-dec] [name=d_text]').nth(1).fill('ZZ قرار ثاني');
await shot('g5-meeting-form'); await p.click('#mtf [type=submit]');
await p.waitForSelector('[data-act=meetEdit]');
const mt = await p.textContent('.wrap');
ok(mt.includes('ZZ قرار صرف دعم رحلة') && mt.includes('ZZ قرار ثاني'), 'decisions saved');
ok(/مكتمل/.test(mt), 'quorum computed (all present)'); await shot('g6-meeting-saved');
ok(errors.length === 0, 'no JS errors: ' + errors.join(' | '));
await browser.close(); console.log(`\n${pass} نجح · ${fail} فشل`); process.exit(fail ? 1 : 0);
